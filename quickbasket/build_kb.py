"""Builds QuickBasket's help-centre knowledge base into kb/ (fictional company, synthetic content).

Deterministic: no AI-written text at build time, fixed seeds, byte-identical PDFs. Customer Policy v4.2
(quickbasket_policy.pdf) stays the source of truth; every place another document disagrees with it is
planted on purpose and listed in kb/conflicts.md.

Usage:
    python quickbasket/build_kb.py            # build the documents, conflicts.md and manifest.json
    python quickbasket/build_kb.py --count    # also measure tokens per document with Gemini count_tokens
"""
import importlib
import json
import os
import re
import shutil
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)
sys.path.insert(0, HERE)

from kb_src import policies  # noqa: E402
from kb_src.common import Ctx  # noqa: E402
from kb_src.render import extract_text, write_pdf  # noqa: E402

OUT = "kb"
MODULES = ["policies", "cities", "promos", "terms", "warranty", "faq", "sop", "playbook"]
COUNT_MODEL = "gemini-3.8-flash"


def _norm(text):
    text = re.sub(r"QuickBasket Customer Policy v[\d.]+ · Effective[^\n]*\n", "", text)
    text = re.sub(r"\bPage \d+\b", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    # A table that crosses a page break repeats its header row; that is layout, not content.
    for b in policies.policy_blocks(policies.V42_PARAMS):
        if b[0] == "table":
            head = " ".join(b[1])
            first = text.find(head)
            if first >= 0:
                text = text[:first + len(head)] + text[first + len(head):].replace(head + " ", "")
    return text


def check_template_matches_v42():
    """The old versions are rendered from a template of v4.2. Prove the template says what v4.2 says."""
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "v42_from_template.pdf")
        write_pdf(path, policies.header(policies.V42_PARAMS), policies.policy_blocks(policies.V42_PARAMS))
        mine, real = _norm(extract_text(path)), _norm(extract_text("quickbasket_policy.pdf"))
    if mine != real:
        a, b = mine.split(" "), real.split(" ")
        i = next((k for k, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
        sys.exit("STOP: the policy template in kb_src/policies.py doesn't match quickbasket_policy.pdf.\n"
                 f"  template: …{' '.join(a[max(0, i - 8):i + 8])}…\n  v4.2 PDF: …{' '.join(b[max(0, i - 8):i + 8])}…")


def write_conflicts(ctx, docs):
    L = ["# Knowledge base: planted conflicts and exceptions (presenter only)", "",
         "Generated by `build_kb.py`. **Customer Policy v4.2 (`01_customer_policy_v4.2.pdf`) is the source of "
         "truth.** Every place another document disagrees with it is planted on purpose and listed in Part A. "
         "Nothing else in the knowledge base is meant to disagree with v4.2. Part B lists legitimate additions "
         "(city rules, launch notices, offer terms) that change an answer without contradicting v4.2.", "",
         f"## Part A. Conflicts with v4.2 ({len(ctx.conflicts)})", "",
         "| # | Topic | Document | Where | It says | v4.2 says | Why it's there |", "|---|---|---|---|---|---|---|"]
    for i, c in enumerate(ctx.conflicts, 1):
        L.append(f"| A{i} | {c['topic']} | `{c['doc']}` | {c['where']} | {c['says']} | {c['v42']} | {c['kind']} |")
    L += ["", f"## Part B. Additions that change an answer ({len(ctx.exceptions)})", "",
          "| # | Topic | Document | Where | It says | Effect |", "|---|---|---|---|---|---|"]
    for i, e in enumerate(ctx.exceptions, 1):
        L.append(f"| B{i} | {e['topic']} | `{e['doc']}` | {e['where']} | {e['says']} | {e['effect']} |")
    L += ["", "## Validity periods of the policy versions", "",
          "| Version | Applies to orders placed | Status |", "|---|---|---|",
          "| v3.2 | 1 March 2025 to 31 December 2025 | Superseded |",
          "| v4.0 | 1 January 2026 to 31 May 2026 | Superseded |",
          "| v4.1 | 1 June 2026 to 30 September 2026 | Superseded |",
          "| v4.2 | from 1 October 2026 | **Current** |", ""]
    with open(os.path.join(OUT, "conflicts.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))


def count_tokens(docs):
    sys.path.insert(0, os.path.dirname(HERE))
    from dotenv import dotenv_values, find_dotenv
    from google import genai
    key = os.environ.get("GOOGLE_API_KEY") or dotenv_values(find_dotenv(usecwd=True)).get("GOOGLE_API_KEY")
    client = genai.Client(api_key=key)
    for d in docs:
        d["tokens"] = client.models.count_tokens(model=COUNT_MODEL, contents=d["text"]).total_tokens


def main():
    check_template_matches_v42()
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    ctx = Ctx(seed=42)
    shutil.copyfile("quickbasket_policy.pdf", os.path.join(OUT, "01_customer_policy_v4.2.pdf"))
    docs = [dict(file="01_customer_policy_v4.2.pdf", title="Customer Policy v4.2 (current, source of truth)",
                 kind="Current policy", fmt="PDF", status="current", version="4.2", valid_from="2026-10-01",
                 valid_to=None)]
    for name in MODULES:
        try:
            mod = importlib.import_module(f"kb_src.{name}")
        except ModuleNotFoundError:
            print(f"(skipping kb_src/{name}.py: not written yet)")
            continue
        docs += mod.build(ctx, OUT)
    docs.sort(key=lambda d: d["file"])
    for d in docs:
        d["text"] = extract_text(os.path.join(OUT, d["file"]))
        d["chars"] = len(d["text"])
    if "--count" in sys.argv:
        count_tokens(docs)
    write_conflicts(ctx, docs)
    manifest = dict(source_of_truth="01_customer_policy_v4.2.pdf", count_model=COUNT_MODEL if "--count" in sys.argv else None,
                    documents=[{k: v for k, v in d.items() if k != "text"} for d in docs])
    with open(os.path.join(OUT, "manifest.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
    sys.stdout.reconfigure(encoding="utf-8")
    print(f"{'Document':46} {'Format':9} {'Chars':>8} {'Tokens':>8}")
    for d in docs:
        print(f"{d['file']:46} {d['fmt']:9} {d['chars']:>8,} {d.get('tokens', '-'):>8}")
    print(f"{'TOTAL':46} {'':9} {sum(d['chars'] for d in docs):>8,} "
          f"{sum(d.get('tokens', 0) for d in docs) or '-':>8}")
    print(f"{len(docs)} documents · {len(ctx.conflicts)} planted conflicts · {len(ctx.exceptions)} exceptions")


if __name__ == "__main__":
    main()
